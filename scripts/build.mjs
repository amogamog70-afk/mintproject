import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, dirname} from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = ['Core', 'Logo', 'Components', 'Storage', 'ThemeManager', 'SaveManager', 'Window', 'init'];
let bundle = '-- MintProject 0.2.0 | Generated by scripts/build.mjs\n';
bundle += 'local factories, cache = {}, {}\nlocal get\n';
for (const name of modules) {
    let source = readFileSync(resolve(root, 'src', name + '.luau'), 'utf8');
    source = source.replace(/require\(script(?:\.Parent)?\.([A-Za-z]+)\)/g, (_, dependency) => {
        if (!modules.includes(dependency)) throw new Error('Unknown dependency: ' + dependency);
        return `get('${dependency}')`;
    });
    if (/require\(script/.test(source)) throw new Error('Unresolved import in ' + name);
    bundle += `factories['${name}'] = function()\n${source}\nend\n`;
}
bundle += `get = function(name)
    if cache[name] == nil then
        assert(factories[name], 'Unknown MintProject module: ' .. tostring(name))
        cache[name] = factories[name]()
    end
    return cache[name]
end
return get('init')\n`;
mkdirSync(resolve(root, 'dist'), {recursive: true});
writeFileSync(resolve(root, 'dist/MintProject.lua'), bundle);
writeFileSync(resolve(root, 'Library.lua'), bundle);
const demo = readFileSync(resolve(root, 'examples/Demo.luau'), 'utf8');
writeFileSync(resolve(root, 'dist/Demo.lua'), `-- Standalone MintProject demonstration. No secondary downloads.\nlocal MintProject = (function()\n${bundle}\nend)()\nlocal makeDemo = (function()\n${demo}\nend)()\nif _G.MintProjectDemo then pcall(function() _G.MintProjectDemo:Destroy() end) end\nlocal window = makeDemo(MintProject)\n_G.MintProjectDemo = window\nreturn window\n`);
console.log('Built dist/MintProject.lua and dist/Demo.lua');
mkdirSync(resolve(root,'addons'),{recursive:true});
for (const name of ['ThemeManager','SaveManager']) {
    const storage=readFileSync(resolve(root,'src/Storage.luau'),'utf8');
    const manager=readFileSync(resolve(root,'src',name+'.luau'),'utf8').replace('require(script.Parent.Storage)','Storage');
    writeFileSync(resolve(root,'addons',name+'.lua'),`-- MintProject ${name}\nlocal Storage=(function()\n${storage}\nend)()\nlocal Manager=(function()\n${manager}\nend)()\nreturn Manager.new()\n`);
}
const body=demo.replace(/^[\s\S]*?return function\([^\n]*\)\n/,'').replace(/\nend\s*$/,'').split('\n').map(line=>line.startsWith('    ')?line.slice(4):line).join('\n');
writeFileSync(resolve(root,'Example.lua'),`local repo = 'https://raw.githubusercontent.com/amogamog70-afk/mintproject/main/'\nlocal Library = loadstring(game:HttpGet(repo .. 'Library.lua'))()\nlocal ThemeManager = loadstring(game:HttpGet(repo .. 'addons/ThemeManager.lua'))()\nlocal SaveManager = loadstring(game:HttpGet(repo .. 'addons/SaveManager.lua'))()\nif _G.MintProjectLibrary then pcall(function() _G.MintProjectLibrary:Unload() end) end\n_G.MintProjectLibrary = Library\nlocal options\n\n${body}\n`);
